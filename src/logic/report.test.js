import { buildTripReportHtml, escapeHtml, reportFileName } from './report';

const people = [
  { id: 'p1', name: 'Rahul' },
  { id: 'p2', name: 'Amit' },
];
const expense = (overrides) => ({
  id: 'e1',
  amount: 1201,
  paidByPid: 'p1',
  categoryId: 'travel',
  date: '2026-12-14',
  description: 'Cab to Baga',
  splitAmongPids: ['p1', 'p2'],
  isDeleted: false,
  ...overrides,
});
const NOW = new Date(2026, 11, 20);

describe('escapeHtml', () => {
  it('neutralises HTML in user text', () => {
    expect(escapeHtml('<b>"Tom" & Jerry\'s</b>')).toBe(
      '&lt;b&gt;&quot;Tom&quot; &amp; Jerry&#39;s&lt;/b&gt;',
    );
    expect(escapeHtml(null)).toBe('');
  });
});

describe('reportFileName', () => {
  it('makes a safe, readable name', () => {
    expect(reportFileName('Goa trip')).toBe('Goa trip – summary.pdf');
    expect(reportFileName('Goa/Pune: 2026?')).toBe('Goa Pune 2026 – summary.pdf');
    expect(reportFileName('')).toBe('Trip – summary.pdf');
  });
});

describe('buildTripReportHtml', () => {
  const activeTrip = {
    name: 'Goa trip',
    startDate: '2026-12-12',
    endDate: '2026-12-16',
    status: 'active',
  };

  it('summarises an open trip as not final, without Settle up', () => {
    const html = buildTripReportHtml(
      { trip: activeTrip, participants: people, expenses: [expense()] },
      NOW,
    );
    expect(html).toContain('Goa trip');
    expect(html).toContain('12 – 16 Dec 2026');
    expect(html).toContain('Not final: the trip is still open');
    expect(html).not.toContain('Settle up');
    expect(html).toContain('₹1,201'); // total and the expense
    expect(html).toContain('+₹600'); // Rahul paid 1,201, share 601
    expect(html).toContain('−₹600');
    expect(html).toContain('Cab to Baga');
    expect(html).toContain('Generated by Trip Manager on 20 Dec 2026');
  });

  it('leaves out deleted expenses', () => {
    const html = buildTripReportHtml(
      {
        trip: activeTrip,
        participants: people,
        expenses: [expense(), expense({ id: 'e2', description: 'Gone', isDeleted: true })],
      },
      NOW,
    );
    expect(html).not.toContain('Gone');
  });

  it('escapes names and descriptions', () => {
    const html = buildTripReportHtml(
      {
        trip: { ...activeTrip, name: '<script>x</script>' },
        participants: [{ id: 'p1', name: 'A & B' }, people[1]],
        expenses: [expense({ description: '<img src=x>' })],
      },
      NOW,
    );
    expect(html).not.toContain('<script>x');
    expect(html).not.toContain('<img src=x>');
    expect(html).toContain('A &amp; B');
  });

  it('includes Settle up and earlier payments once closed', () => {
    const html = buildTripReportHtml(
      {
        trip: { ...activeTrip, status: 'final' },
        participants: people,
        expenses: [expense()],
        settlements: [
          { fromPid: 'p2', toPid: 'p1', amount: 600, isPaid: true, isRecordedPayment: true },
          { fromPid: 'p2', toPid: 'p1', amount: 1, isPaid: false, isRecordedPayment: false },
        ],
      },
      NOW,
    );
    expect(html).not.toContain('Not final');
    expect(html).toContain('Settle up');
    expect(html).toContain('Amit pays Rahul');
    expect(html).toContain('Not paid');
    expect(html).toContain('Earlier payments');
  });

  it('says when everyone is square', () => {
    const html = buildTripReportHtml(
      { trip: { ...activeTrip, status: 'closed' }, participants: people, expenses: [] },
      NOW,
    );
    expect(html).toContain('Everyone’s settled up. Nothing to pay.');
    expect(html).toContain('No expenses.');
  });

  it('lists spending by category with percentages', () => {
    const html = buildTripReportHtml(
      {
        trip: activeTrip,
        participants: people,
        expenses: [expense(), expense({ id: 'e2', amount: 3603, categoryId: 'food' })],
      },
      NOW,
    );
    expect(html).toContain('75%');
    expect(html).toContain('25%');
  });
});
